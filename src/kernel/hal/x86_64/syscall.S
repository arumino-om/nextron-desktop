/*
 * syscall.S — システムコールの入口 (x86_64)
 *
 * arm64 の vectors.S の `.Lsync_el0`（svc の枝）に当たる。
 *
 * ------------------------------------------------------------------------
 * arm64 との構造差 — syscall はスタックを切り替えない
 * ------------------------------------------------------------------------
 *
 * arm64 の svc は**例外**なので、SP が SP_EL0 から SP_EL1 へ自動で
 * 切り替わり、戻り先 (ELR_EL1) とフラグ (SPSR_EL1) もハードウェアが
 * 退避する。x86 の `syscall` は例外ではなく**ただの分岐**で、
 *
 *   - RSP はユーザのまま（カーネルスタックへの載せ替えはソフトの仕事）
 *   - 戻り先が RCX、RFLAGS が R11 に入る（どちらも壊してはいけない）
 *   - CS / SS だけが STAR の値に差し替わる
 *
 * という形になる。だから入口で自分でスタックを載せ替える。置き場は
 * per-CPU 領域で、`swapgs` で %gs をカーネル側に切り替えてから引く
 * （cpu.c の PerCpu。+0 がカーネル SP、+8 がユーザ RSP の置き場）。
 *
 * ------------------------------------------------------------------------
 * システムコールの約束 (本OS の ABI。x86_64)
 * ------------------------------------------------------------------------
 *
 *   rax            システムコール番号
 *   rdi rsi rdx    引数 1〜3
 *   r10 r8 r9      引数 4〜6   ← **rcx ではなく r10**
 *   rax            戻り値
 *
 * 第 4 引数に rcx を使えないのは、`syscall` が rcx を戻り先 RIP で
 * 潰すためである。C 側 (`btron_syscall_entry`) は System V の並び
 * （rdi rsi rdx rcx r8 r9 + 7 番目はスタック）で受けるので、入口で
 * r10 を rcx へ移し、番号をスタックへ積む。
 *
 * 【規律 R31 と同じ姿勢】**嘘の成功を返さない。** 番号が範囲外なら
 * C 側がエラーを返す。ここでは積み替えだけを行う。
 */

    .section .text, "ax"

    .globl btron_syscall_stub
    .type btron_syscall_stub, @function
btron_syscall_stub:
    swapgs                          /* %gs をカーネルの per-CPU へ */
    movq    %rsp, %gs:8             /* ユーザ RSP を預ける */
    movq    %gs:0, %rsp             /* このタスクのカーネルスタックへ */

    /* 戻りに要るものを積む。順番は下の復元と合わせる。 */
    pushq   %gs:8                   /* ユーザ RSP */
    pushq   %r11                    /* ユーザの RFLAGS */
    pushq   %rcx                    /* ユーザの戻り先 RIP */

    /* System V の並びへ直す。**rsp は 16 の倍数になっている** ——
     * カーネルスタックの先頭が 16 整列で、ここまで 4 回積んだため
     * （次の push で 32 バイト = 0 mod 16）。 */
    pushq   %rax                    /* 7 番目の引数 = 番号 */
    movq    %r10, %rcx              /* 第 4 引数 */
    call    btron_syscall_entry
    addq    $8, %rsp                /* 番号を捨てる。戻り値は rax のまま */

    popq    %rcx                    /* 戻り先 RIP */
    popq    %r11                    /* RFLAGS */
    popq    %rsp                    /* ユーザ RSP。以後カーネル側は触れない */
    swapgs
    sysretq
